<#
.SYNOPSIS
  Converts a SigmaStudio ADAU1701 self-boot image (E2Prom.bin or E2Prom.Hex)
  into a C header for the Audio-DSP-Lab firmware.

.DESCRIPTION
  SigmaStudio writes the image to "<project>_IC 2\E2Prom.bin" (binary) and
  "E2Prom.Hex" (the same bytes as "0x01 , 0x00 , ..." text). Either is
  accepted. The header defines
    static const uint8_t <Name>[] = { ... };
    static const size_t <Name>Length = sizeof(<Name>);

.EXAMPLE
  .\Convert-E2PromImage.ps1 -Source "...\ADAU1701_Generator_IC 2\E2Prom.bin" `
      -Name DspImageGenerator `
      -Destination ..\firmware\AudioDspLab\DspImageGenerator.h
#>
param(
  [Parameter(Mandatory)] [string] $Source,
  [Parameter(Mandatory)] [ValidatePattern('^[A-Za-z_][A-Za-z0-9_]*$')] [string] $Name,
  [Parameter(Mandatory)] [string] $Destination
)

$ErrorActionPreference = 'Stop'

$sourcePath = (Resolve-Path -LiteralPath $Source).Path
if ($sourcePath -match '\.hex$') {
  $text = Get-Content -LiteralPath $sourcePath -Raw
  $bytes = [byte[]]([regex]::Matches($text, '0x([0-9A-Fa-f]{2})') |
    ForEach-Object { [Convert]::ToByte($_.Groups[1].Value, 16) })
} else {
  $bytes = [System.IO.File]::ReadAllBytes($sourcePath)
}

if ($bytes.Length -eq 0) { throw "No bytes found in $sourcePath" }
if ($bytes.Length -gt 32768) { throw "Image is $($bytes.Length) bytes; the 24C256 holds 32768" }
if ($bytes[0] -ne 0x01) { throw "First byte is 0x{0:X2}; an ADAU1701 self-boot image starts with a write message (0x01)" -f $bytes[0] }

$lines = for ($i = 0; $i -lt $bytes.Length; $i += 16) {
  $count = [Math]::Min(16, $bytes.Length - $i)
  '  ' + (($bytes[$i..($i + $count - 1)] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ','
}

$guard = ($Name.ToUpperInvariant()) + '_H'
$header = @"
// Generated by tools\Convert-E2PromImage.ps1 - do not edit.
// Source: $(Split-Path -Leaf (Split-Path -Parent $sourcePath))\$(Split-Path -Leaf $sourcePath)
// Length: $($bytes.Length) bytes

#ifndef $guard
#define $guard

#include <stdint.h>
#include <stddef.h>

static const uint8_t $Name[] = {
$($lines -join "`n")
};
static const size_t ${Name}Length = sizeof($Name);

#endif
"@

$destinationPath = [System.IO.Path]::GetFullPath((Join-Path (Get-Location) $Destination))
[System.IO.File]::WriteAllText($destinationPath, $header.Replace("`r`n", "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("{0}: {1} bytes -> {2}" -f $Name, $bytes.Length, $destinationPath)
